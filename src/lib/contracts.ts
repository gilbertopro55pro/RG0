// The system's starting contract terms — every photographer gets this by default, but can
// replace it entirely with their own terms (Settings → תבנית חוזה, photographers.custom_contract_terms).
// Kept as a function (not a plain constant) only because clause טז names the photographer.
export function defaultContractTerms(photographerName: string): string {
  return `ד. סרט החתונה יימסר תוך 35 ימי עבודה מיום בחירת השירים לעריכה ע״י הלקוח, ומותנה בסיום ההתחייבות הכספית קודם לכך.
ה. דרישות צילום נוספות אשר אינן מצוינות בהסכם זה יבוצעו בהתאם לדרישות מוגדרות היטב, מסוכמות ומתומחרות ויוספו על ידי שני הצדדים כנספח חתום להסכם שירות זה תוך ציון תוספת העלויות למחיר שנקבע בחוזה בסיסי.
ו. תוכן הנושאים בצילומים יקבע על ידי הצלם במהלך האירוע בהתאם לראות עיניו ותוך התחשבות בבקשות של הלקוח. באחריות הלקוח למנות אדם אחד לפחות אשר מכיר את האורחים או הוא עצמו אשר יציג בני משפחה קרובים ומוזמנים אחרים שאותם חשוב במיוחד ללקוח לצלם.
ז. במקרה של כוח עליון ו/או חבלה בזדון או במזיד (גשם, שרפה, מצב חירום וכו׳) ו/או פעולת לייזרים או התזת מים או כל חומר אחר שמסכן את הציוד ו/או הבריאות, הצלם רשאי להפסיק עבודתו בזמן אמת כדי לשמור על חייו, בריאותו והציוד שלו כראות עיניו ובאופן מידי ללא עוררין.
ח. במקרה של הזמנת ספקי צילום נוספים מצד הלקוח (למשל: "צלמי סושיאל", מגנטים וכו׳): לא נישא באחריות על עיכובים ביום הצילום ו/או פספוס רגעים חשובים שנגרם על ידי אותו ספק נוסף (למשל הסתרה של המצולמים ו/או עיכוב בצילומי החוץ וכו').
ט. בעת הזמנת אלבום דיגיטלי ו/או עריכת סרט העריכה תתבצע לפי הסגנון שהוצג ובהתאם לחומר המצולם ורעיונותיו. הסקיצה של האלבום תישלח ללקוח לאישור לפני הדפסה. הסרט והתקציר ישלחו ללקוח לצפייה ולאישור תוך 28 ימי עסקים, לאחר מכן לא יתאפשרו שינויים בעריכה.
י. במקרה של ביטול הזמנת העבודה שלא בעקבות מצב חירום כאמור בסעיף יג׳: ביטול 21 יום או יותר לפני מועד האירוע, יחויב הלקוח בסך המקדמה. ביטול בפחות מ-21 יום לפני מועד האירוע, יחויב הלקוח במחצית מהתשלום המלא. בקשת הביטול תבוצע בכתב.
יא. הבהרות בקשר לצילומי וידאו:
1. הצלם יבצע עריכה של החומר המצולם, סגנון העריכה יהיה קרוב ככל הניתן לדוגמאות אותן ראה הלקוח ובהתאם לאופי האירוע ותנאי הצילום.
2. מובהר כי הצלם לא אחראי על בעיות סאונד הקשורה למערכת ההגברה של האולם/להקה/תקליטן/מנחה וכו׳.
3. הובהר על ידי הצלם כי הוא אינו אחראי על איכות וידאו עקב בעיית תאורה הקשורה למערכת התאורה של האולם או של כל מערכת תאורה מטעם המזמין.
4. במקרה של הזמנת צילום רחפן, מובהר בזאת למזמין כי במידה וימצאו תנאים שלא מאפשרים הטסה וצילום מהרחפן בגלל מזג האוויר או אזור האסור בהטסת רחפן – הרחפן לא יוטס.
5. תיקונים ושינויים בסרט: לאחר הגשת הסרט הערוך והתקציר, לא יתקבלו בקשות להחלפת מוזיקה ו/או השירים שנבחרו על ידי הלקוח קודם העריכה, החל מסבב התיקונים השלישי תגבה תוספת 200₪ לשעת עריכה (החל משעתיים).
יב. מובהר למזמין, כי כל חומרי הגלם ישמרו על ידי הצלם חודש לאחר מסירת החומרים והמוצרים הסופיים כפי שסוכם. המזמינים מתחייבים לבחור את השירים לסרט עד שבועיים מיום האירוע, המזמין רשאי לאשר לצלמים לבחור את השירים לסרט ובזאת הסכים כי לא ניתן להחליף את השירים לאחר העריכה.
יג. במקרה של דחיית האירוע/שינוי מיקום כתוצאה מכח עליון, מצב חירום או מלחמה, ואולם במידה ולא ימצא פתרון או יבוטל האירוע – תוחזר המקדמה במלואה.
יד. מוסכם בין הצדדים כי אחריותו של הצלם במקרה של תקלה ו/או קלקול ו/או פגם מכל סוג שהוא, בין בחומר הגלם ובעבודות המוזמנות ובין מתן בשירותים המוזמנים, ובגין כל פגיעה ו/או מחדל של הצלם ו/או של כל מי שמטעמו, בכל מקרה ולכל היותר יפוצה הלקוח עד לסך שהינו שווה ערך לסכום הנקוב בסעיף ג׳ ("הסדרי תשלום") אשר שולם בפועל, ובכל מקרה לא תעלה על סך זה.
טו. לצלם שמורות זכויות היוצרים בתמונות לרבות זכות שימוש לצורך קידום מכירות, אתר אינטרנט, אלבומי דוגמא וכו׳. במידה והמזמין לא רוצה שהצלם יעשה שימוש מסחרי בתמונות יש להודיע מראש ובכתב.
טז. ${photographerName} – צילום אירועים מתחייב להסכם זה, כל עוד לא בוצע שינוי בהסכם שלא בהסכמת 2 הצדדים.`;
}

export function generateContractText({
  photographerName,
  photographerPhone,
  signature,
  customTerms,
  clientName,
  clientPhone,
  eventDate,
  eventLocation,
  packageLabelText,
  depositAmount,
  balanceAmount,
  balanceDueDate,
}: {
  photographerName: string;
  photographerPhone: string;
  signature: string | null;
  // The photographer's own contract terms (Settings → תבנית חוזה). null/empty falls back to
  // defaultContractTerms — see photographers.custom_contract_terms.
  customTerms: string | null;
  clientName: string;
  clientPhone: string | null;
  eventDate: string;
  eventLocation: string | null;
  packageLabelText: string;
  depositAmount: number;
  balanceAmount: number;
  balanceDueDate: string | null;
}): string {
  const formattedDate = new Date(eventDate).toLocaleDateString("he-IL");
  const total = depositAmount + balanceAmount;
  const formattedDueDate = balanceDueDate ? new Date(balanceDueDate).toLocaleDateString("he-IL") : "מועד האירוע";
  const termsBody = customTerms?.trim() || defaultContractTerms(photographerName);

  return `הסכם הזמנת שירותי צילום

בין: ${photographerName} (${photographerPhone}) ("הצלם")
לבין: ${clientName}${clientPhone ? ` (${clientPhone})` : ""} ("הלקוח/ה")

1. פרטי האירוע
תאריך האירוע: ${formattedDate}
מיקום: ${eventLocation || "יעודכן"}
חבילה: ${packageLabelText}

2. תמורה ותשלומים
סכום כולל: ₪${total}
מקדמה: ₪${depositAmount} (לתשלום עם סגירת ההזמנה)
יתרה: ₪${balanceAmount} (לתשלום עד ${formattedDueDate})

3. תנאים כלליים
הצלם מתחייב לספק את שירותי הצילום כמפורט בחבילה שנבחרה, במועד ובמיקום שנקבעו לעיל.
כל שינוי בתנאי הסכם זה ייעשה בהסכמת שני הצדדים בכתב.

לפירוט המלא
${termsBody}

4. אישור וחתימה
בחתימתי (הקלדת שם מלא) להלן, אני מאשר/ת כי קראתי את תנאי ההסכם, אני מסכים/ה לתוכנו, וכי חתימה זו מהווה אישור אלקטרוני מחייב לפי חוק חתימה אלקטרונית, התשס"א-2001.

${signature ? `\n${signature}` : ""}`;
}
